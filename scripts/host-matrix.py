#!/usr/bin/env python3
"""Generate and check a root's host matrix: each feature's status on each host.

The feature ids are the root's own, from <root>/hosts/features.yaml. Each host reports
its statuses in the `features:` of <root>/hosts/<host>/host.yaml (schema:
build/host_schema.py), one of native|equivalent|inline|absent. An `absent` entry
names the loss in its note, because a host that drops a feature has to say what is
lost (a silent gap reads as support).

The matrix is written to <the root's git toplevel>/docs/host-matrix.md, or to --out.
Without --root, the root is this repo.

  --write                 render the matrix
  --check --hosts a,b     exit 1 when a listed host has no host.yaml, lacks an id,
                          reports an id features.yaml does not define, or has an
                          `absent` entry with no note; or when the written matrix is
                          missing or differs from what the sources render. Writes
                          nothing.

Exit 0 on success, 1 on a failed check, 2 on a usage error or an unreadable source.

Usage:
  python3 scripts/host-matrix.py --write
  python3 scripts/host-matrix.py --check --hosts claude,codex
  python3 scripts/host-matrix.py --root <dir> --write [--out <file>]
"""
import argparse
import os
import subprocess
import sys

sys.dont_write_bytecode = True
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "build"))
import host_schema  # noqa: E402

MATRIX = os.path.join("docs", "host-matrix.md")


class Refusal(Exception):
    pass


def load_features(root):
    """[(id, what)] from <root>/hosts/features.yaml, in its order."""
    path = os.path.join(root, "hosts", "features.yaml")
    try:
        doc = host_schema.load_yaml(path)
    except OSError as e:
        raise Refusal(f"{path}: {e}") from None
    except host_schema.SchemaError as e:
        raise Refusal(str(e)) from None
    items = doc.get("features") if isinstance(doc, dict) else None
    if not isinstance(items, list) or not items or set(doc) != {"features"}:
        raise Refusal(f"{path} must hold exactly `features:`, a non-empty list")
    out, seen = [], set()
    for i, ft in enumerate(items):
        if not isinstance(ft, dict) or set(ft) != {"id", "what"} \
                or not all(isinstance(ft[k], str) and ft[k] for k in ("id", "what")):
            raise Refusal(f"{path}: features[{i}] must have exactly a string id and what")
        if "\n" in ft["what"] or "\n" in ft["id"]:
            raise Refusal(f"{path}: features[{i}] must be one line")
        if ft["id"] in seen:
            raise Refusal(f"{path}: feature {ft['id']!r} is listed twice")
        seen.add(ft["id"])
        out.append((ft["id"], ft["what"]))
    return out


def load_hosts(root):
    """{host: host.yaml config} for every hosts/<host>/ holding a host.yaml."""
    base = os.path.join(root, "hosts")
    if not os.path.isdir(base):
        raise Refusal(f"{root} has no hosts/ directory")
    hosts = {}
    for name in sorted(os.listdir(base)):
        path = os.path.join(base, name, "host.yaml")
        if os.path.isfile(path):
            try:
                hosts[name] = host_schema.load_host(path, name)
            except host_schema.SchemaError as e:
                raise Refusal(str(e)) from None
            for f in hosts[name]["features"]:
                if f["note"] and "\n" in f["note"]:
                    raise Refusal(f"{path}: the note on {f['id']} must be one line")
    return hosts


def cell_text(text):
    """Text safe inside a Markdown table cell."""
    return text.replace("|", "\\|")


def cell(entry):
    return entry["status"] if entry else "—"


def render(root, top, features, hosts):
    names = sorted(hosts, key=lambda h: (h != "claude", h))
    src = os.path.relpath(os.path.join(root, "hosts"), top)
    lines = [
        "<!-- Generated by host-matrix.py from "
        f"{src}/*/host.yaml and {src}/features.yaml. Do not edit by hand. -->",
        "# Host matrix", "",
        "Each feature's status per host: `native` (the host does it as the identity host "
        "does), `equivalent` (another mechanism gives the same result), `inline` (the "
        "model does it in the conversation, with no host machinery), `absent` (not "
        "available; the note says what is lost). `—` means the host reports no status.", "",
        "| Feature | What | " + " | ".join(names) + " |",
        "|---|---|" + "---|" * len(names),
    ]
    by_host = {h: {f["id"]: f for f in hosts[h]["features"]} for h in names}
    for fid, what in features:
        lines.append(f"| `{fid}` | {cell_text(what)} | "
                     + " | ".join(cell(by_host[h].get(fid)) for h in names) + " |")
    notes = [(h, fid, by_host[h][fid]) for fid, _ in features for h in names
             if fid in by_host[h] and by_host[h][fid]["note"]]
    if notes:
        lines += ["", "## Notes", ""]
        lines += [f"- **{h} / `{fid}`** ({e['status']}): {e['note']}" for h, fid, e in notes]
    return "\n".join(lines) + "\n"


def completeness(features, hosts, wanted):
    ids = [fid for fid, _ in features]
    problems = []
    for h in wanted:
        if h not in hosts:
            problems.append(f"{h} has no hosts/{h}/host.yaml")
            continue
        have = {f["id"]: f for f in hosts[h]["features"]}
        problems += [f"{h} lacks {fid}" for fid in ids if fid not in have]
        problems += [f"{h} reports {fid}, which hosts/features.yaml does not define"
                     for fid in have if fid not in ids]
        problems += [f"{h} reports {fid} absent with no note naming the loss"
                     for fid, f in have.items() if f["status"] == "absent" and not f["note"]]
    return problems


def toplevel(root):
    r = subprocess.run(["git", "-C", root, "rev-parse", "--show-toplevel"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise Refusal(f"{root} is not inside a git work tree")
    return os.path.realpath(r.stdout.strip())


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=REPO, help="the core/ + hosts/ root (default: this repo)")
    ap.add_argument("--out", help="the matrix file (default: <toplevel>/docs/host-matrix.md)")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--hosts", help="with --check: the comma-separated hosts that must be "
                    "complete")
    args = ap.parse_args()
    if args.check and not args.hosts:
        ap.error("--check needs --hosts")
    if args.write and args.hosts:
        ap.error("--hosts goes with --check")
    try:
        root = os.path.realpath(args.root)
        top = toplevel(root)
        out = os.path.abspath(args.out) if args.out else os.path.join(top, MATRIX)
        features = load_features(root)
        hosts = load_hosts(root)
        text = render(root, top, features, hosts)
    except Refusal as e:
        print(f"host-matrix: {e}", file=sys.stderr)
        return 2
    shown = os.path.relpath(out, top) if out.startswith(top + os.sep) else out
    if args.write:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"host-matrix: wrote {shown} ({len(features)} feature(s), {len(hosts)} host(s))")
        return 0
    wanted = [h for h in args.hosts.split(",") if h]
    if not wanted:
        print("host-matrix --check: --hosts names no host, so it would check nothing",
              file=sys.stderr)
        return 2
    problems = completeness(features, hosts, wanted)
    if not os.path.isfile(out):
        problems.append(f"{shown} does not exist — run --write")
    else:
        with open(out, encoding="utf-8") as fh:
            if fh.read() != text:
                problems.append(f"{shown} is stale — run --write")
    if problems:
        print(f"host-matrix --check: {len(problems)} problem(s):", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1
    print(f"host-matrix --check: {', '.join(wanted)} complete; {shown} current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
